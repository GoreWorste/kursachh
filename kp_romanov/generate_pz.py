def build_docx(md_path: Path) -> tuple[Path, int, int]:
  global figure_counter, table_counter
  figure_counter = 0
  table_counter = 0

  doc = open_pz_document()

  # титульный блок (краткий)
  t = doc.add_paragraph(TOPIC.upper(), style="ПЗ_Заголовок1")
  t.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
  t.paragraph_format.first_line_indent = Cm(0)
  doc.add_paragraph(f"Пояснительная записка\n{STUDENT}", style="ПЗ_Основной").paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
  doc.add_page_break()

  md_text = md_path.read_text(encoding="utf-8")
  parse_markdown_to_docx(doc, md_text)
  add_conclusion_and_bibliography(doc)
  add_appendix_a(doc)
  add_appendix_b(doc)
  add_appendix_v(doc)
  add_appendix_g(doc)
  add_appendix_d(doc)

  out = DOCX_OUT
  try:
    doc.save(str(out))
  except PermissionError:
    out = DOCX_ALT
    doc.save(str(out))
  return out, figure_counter, table_counter


def estimate_pages(docx_path: Path) -> int:
  """Оценка числа страниц по объёму текста (~1800 знаков на страницу)."""
  try:
    from docx import Document as D
    d = D(str(docx_path))
    chars = sum(len(p.text) for p in d.paragraphs)
    for t in d.tables:
      for row in t.rows:
        for cell in row.cells:
          chars += len(cell.text)
    return max(1, chars // 1800)
  except Exception:
    return 0


def main() -> int:
  passport, synopsis = _read_context()
  if not passport:
    print("Предупреждение: ЛИНГВИСТИЧЕСКИЙ_ПАСПОРТ.md не найден", file=sys.stderr)
  if not synopsis:
    print("Предупреждение: ТЕХНИЧЕСКИЙ_КОНСПЕКТ.md не найден", file=sys.stderr)

  print("Генерация Markdown...")
  md_path = write_markdown()
  print(f"  MD: {md_path}")

  print("Сборка DOCX...")
  docx_path, fig_n, tbl_n = build_docx(md_path)
  pages = estimate_pages(docx_path)

  print("\n=== Результат ===")
  print(f"Markdown:     {md_path}")
  print(f"DOCX:         {docx_path}")
  print(f"Рисунков:     {fig_n}")
  print(f"Таблиц (осн.): {tbl_n}")
  print(f"Оценка страниц: ~{pages}")
  print(f"Дата:         {datetime.now().strftime('%d.%m.%Y %H:%M')}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
