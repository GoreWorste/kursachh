def collect_source_files() -> list[Path]:
  result: list[Path] = []
  for root_dir in (WEB, MOBILE):
    if not root_dir.is_dir():
      continue
    for path in sorted(root_dir.rglob("*")):
      if not path.is_file():
        continue
      if path.suffix not in SOURCE_SUFFIXES and path.name != ".env.example":
        continue
      if any(ex in path.parts for ex in EXCLUDE_DIRS):
        continue
      result.append(path)
  return sorted(result, key=lambda p: str(p.relative_to(PROJECT)))


def _add_code_block(doc: Document, text: str, max_lines: int | None = None) -> int:
  lines = text.splitlines()
  if max_lines:
    lines = lines[:max_lines]
  code_style = "ПЗ_Код Знак" if _style_exists(doc, "ПЗ_Код Знак") else "ПЗ_Код"
  for line in lines:
    p = doc.add_paragraph(line if line else " ", style=code_style)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
  return len(lines)


