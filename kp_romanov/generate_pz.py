def _add_heading(doc: Document, text: str, level: int) -> None:
  clean = re.sub(r"^\d+(\.\d+)*\s+", "", text).strip()
  if clean.upper() == "ВВЕДЕНИЕ":
    p = doc.add_paragraph("ВВЕДЕНИЕ", style="ПЗ_Заголовок1")
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    for run in p.runs:
      run.bold = False
      run.font.size = Pt(16)
    return
  upper = clean.upper()
  if upper in ("ОБЩАЯ ЧАСТЬ", "СПЕЦИАЛЬНАЯ ЧАСТЬ", "ТЕХНОЛОГИЧЕСКАЯ ЧАСТЬ", "ЗАКЛЮЧЕНИЕ",
               "СПИСОК ИСПОЛЬЗУЕМЫХ МАТЕРИАЛОВ"):
    p = doc.add_paragraph(clean.upper(), style="ПЗ_Заголовок1")
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    for run in p.runs:
      run.bold = True
    return
  doc.add_paragraph(clean or text, style=f"ПЗ_Заголовок{min(level, 3)}")


def _parse_table_row(line: str) -> list[str]:
  line = line.strip()
  if line.startswith("|"):
    line = line[1:]
  if line.endswith("|"):
    line = line[:-1]
  return [c.strip() for c in line.split("|")]


def _add_markdown_table(doc: Document, rows: list[list[str]], caption: str | None) -> None:
  global table_counter
  if not rows:
    return
  table_counter += 1
  if caption:
    cap = caption.replace("**", "").strip()
    if cap.startswith("Таблица –"):
      cap = f"Таблица {table_counter} – {cap.split('–', 1)[1].strip()}"
    elif not re.match(r"^Таблица\s+\d+", cap, re.I):
      cap = f"Таблица {table_counter} – {cap}"
    cap = cap.replace("**", "")
    p_cap = doc.add_paragraph(cap, style="ПЗ_ТаблицаЗаголовок")
    p_cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p_cap.paragraph_format.first_line_indent = Cm(0)
  ncols = max(len(r) for r in rows)
  table = doc.add_table(rows=len(rows), cols=ncols)
  table.style = "Table Grid"
  merge_from: dict[int, int] = {}
  for ri, row in enumerate(rows):
    if len(row) == 1 and row[0].startswith(">>"):
      label = row[0][2:].strip()
      cell = table.rows[ri].cells[0]
      cell.text = label
      if ncols > 1:
        cell.merge(table.rows[ri].cells[ncols - 1])
      for p in cell.paragraphs:
        p.style = doc.styles["ПЗ_ТаблицаТекст"]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
      _set_cell_shading(cell)
      continue
    if row and row[0] == "^":
      merge_from[ri] = ri - 1
    for ci in range(ncols):
      val = row[ci] if ci < len(row) else ""
      if val == "^":
        continue
      cell = table.rows[ri].cells[ci]
      cell.text = val
      for p in cell.paragraphs:
        p.style = doc.styles["ПЗ_ТаблицаТекст"]
      if ri == 0:
        _set_cell_shading(cell)
  for ri, src in merge_from.items():
    if src < 0:
      continue
    for ci in (0, 1):
      if ci >= ncols:
        break
      try:
        table.rows[src].cells[ci].merge(table.rows[ri].cells[ci])
      except Exception:
        pass


def _add_figure(doc: Document, filename: str, caption: str) -> None:
  global figure_counter
  figure_counter += 1
  img_path = DIAGRAMS / filename
  if img_path.is_file():
    p = doc.add_paragraph(style="ПЗ_Рисунок")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(img_path), width=Inches(5.5))
  else:
    _add_paragraph(doc, f"[Изображение: {filename} — файл не найден в diagrams/]", center=True)
  cap_text = caption.strip()
  if not cap_text.lower().startswith("рисунок"):
    cap_text = f"Рисунок {figure_counter} – {cap_text}"
  elif "–" not in cap_text and "." in cap_text:
    cap_text = re.sub(r"^([Рр]исунок\s+\d+)\.\s*", r"\1 – ", cap_text, count=1)
  _add_paragraph(doc, cap_text, style="ПЗ_Рисунок", center=True)


def parse_markdown_to_docx(doc: Document, md_text: str) -> None:
  global figure_counter, table_counter
  lines = md_text.splitlines()
  i = 0
  buf: list[str] = []

  def flush_paragraphs() -> None:
    nonlocal buf
    if not buf:
      return
    text = " ".join(buf).strip()
    buf = []
    if not text:
      return
    if text.startswith("•"):
      for part in re.split(r"(?<=\n)(?=•)", text):
        part = part.strip()
        if part:
          doc.add_paragraph(part, style="ПЗ_СписокМаркированный")
    else:
      _add_paragraph(doc, text)

  while i < len(lines):
    line = lines[i]
    stripped = line.strip()

    if not stripped:
      flush_paragraphs()
      i += 1
      continue

    hm = HEADING_RE.match(stripped)
    if hm:
      flush_paragraphs()
      level = len(hm.group(1))
      _add_heading(doc, hm.group(2).strip(), level)
      i += 1
      continue

    fm = FIGURE_RE.match(stripped)
    if fm:
      flush_paragraphs()
      _add_figure(doc, fm.group(1).strip(), fm.group(2).strip())
      i += 1
      continue

    if stripped.startswith("|") and i + 1 < len(lines) and TABLE_SEP_RE.match(lines[i + 1].strip()):
      flush_paragraphs()
      table_rows = [_parse_table_row(stripped)]
      i += 2
      while i < len(lines) and lines[i].strip().startswith("|"):
        table_rows.append(_parse_table_row(lines[i].strip()))
        i += 1
      while i < len(lines) and not lines[i].strip():
        i += 1
      caption = None
      if i < len(lines) and lines[i].strip().startswith("**Таблица"):
        caption = lines[i].strip().strip("*")
        i += 1
      _add_markdown_table(doc, table_rows, caption)
      continue

    if stripped.startswith("**Таблица"):
      flush_paragraphs()
      _add_paragraph(doc, stripped.strip("*"), style="ПЗ_ТаблицаЗаголовок", center=True)
      i += 1
      continue

    if stripped.startswith("•"):
      flush_paragraphs()
      doc.add_paragraph(stripped, style="ПЗ_СписокМаркированный")
      i += 1
      continue

    buf.append(stripped)
    i += 1
  flush_paragraphs()


