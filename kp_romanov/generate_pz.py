def _md_table(rows: list[list[str]], caption: str) -> str:
    """Собрать markdown-таблицу с подписью."""
    if not rows:
        return ""
    header = "| " + " | ".join(rows[0]) + " |"
    sep = "| " + " | ".join("---" for _ in rows[0]) + " |"
    body = ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return "\n".join([header, sep] + body + [caption]) + "\n"


