def setup_document_styles(doc: Document) -> None:
  """Создать именованные стили ПЗ (как в «Пример ПЗ КП 1.docx»)."""
  if _style_exists(doc, "ПЗ_Основной"):
    normal = doc.styles["ПЗ_Основной"]
  else:
    normal = doc.styles["Normal"]
    normal.name = "ПЗ_Основной"
  _apply_style_font(normal, size=14)
  pf = normal.paragraph_format
  pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
  pf.line_spacing = 1.5
  pf.first_line_indent = Cm(1.25)
  pf.space_after = Pt(0)
  pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

  for lvl, sz, bold in ((1, 16, True), (2, 14, True), (3, 14, True)):
    sn = f"ПЗ_Заголовок{lvl}"
    st = doc.styles[sn] if _style_exists(doc, sn) else doc.styles.add_style(sn, 1)
    _apply_style_font(st, size=sz, bold=bold)
    st.paragraph_format.space_before = Pt(12 if lvl > 1 else 0)
    st.paragraph_format.space_after = Pt(6)
    st.paragraph_format.first_line_indent = Cm(0)
    st.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    st.paragraph_format.keep_with_next = True

  for sn, left in (
      ("ПЗ_СписокМаркированный", Cm(1.25)),
      ("ПЗ_СписокНумерованный", Cm(1.25)),
  ):
    bl = doc.styles[sn] if _style_exists(doc, sn) else doc.styles.add_style(sn, 1)
    _apply_style_font(bl, size=14)
    bl.paragraph_format.left_indent = left
    bl.paragraph_format.first_line_indent = Cm(0)
    bl.paragraph_format.line_spacing = 1.5

  fig = doc.styles["ПЗ_Рисунок"] if _style_exists(doc, "ПЗ_Рисунок") else doc.styles.add_style("ПЗ_Рисунок", 1)
  _apply_style_font(fig, size=14)
  fig.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
  fig.paragraph_format.first_line_indent = Cm(0)
  fig.paragraph_format.space_before = Pt(6)
  fig.paragraph_format.space_after = Pt(12)

  th = doc.styles["ПЗ_ТаблицаЗаголовок"] if _style_exists(doc, "ПЗ_ТаблицаЗаголовок") else doc.styles.add_style("ПЗ_ТаблицаЗаголовок", 1)
  _apply_style_font(th, size=14, bold=True)
  th.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
  th.paragraph_format.first_line_indent = Cm(0)

  tt = doc.styles["ПЗ_ТаблицаТекст"] if _style_exists(doc, "ПЗ_ТаблицаТекст") else doc.styles.add_style("ПЗ_ТаблицаТекст", 1)
  _apply_style_font(tt, size=12)
  tt.paragraph_format.first_line_indent = Cm(0)
  tt.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER

  for sn in ("ПЗ_Код", "ПЗ_Код Знак"):
    cd = doc.styles[sn] if _style_exists(doc, sn) else doc.styles.add_style(sn, 1)
    _apply_style_font(cd, size=10)
    cd.paragraph_format.first_line_indent = Cm(0)
    cd.paragraph_format.left_indent = Cm(0)
    cd.paragraph_format.line_spacing = 1.0
    cd.font.name = "Courier New"
    rpr = cd.element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), "Courier New")
    rfonts.set(qn("w:hAnsi"), "Courier New")

  ap = doc.styles["ПЗ_ПриложениеЗаголовок"] if _style_exists(doc, "ПЗ_ПриложениеЗаголовок") else doc.styles.add_style("ПЗ_ПриложениеЗаголовок", 1)
  _apply_style_font(ap, size=16, bold=True)
  ap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
  ap.paragraph_format.first_line_indent = Cm(0)


